# Generate nested JSON per language
# ============================================================

def to_nested(flat, lang):
    out = {}
    for slug, vals in flat.items():
        parts = slug.split(".")
        node = out
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = vals[lang]
    return out

base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
trdir = os.path.join(base, "quickshell", "translations")
for lang in ["ru", "en", "de", "ja", "zh"]:
    nested = to_nested(D, lang)
    with open(os.path.join(trdir, lang + ".json"), "w", encoding="utf-8") as f:
        json.dump(nested, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{lang}.json: {len(D)} keys written")

# Reverse map: russian -> slug (for QML rewriting)
rev = {}
for slug, vals in D.items():
    rev.setdefault(vals["ru"], []).append(slug)
    if "en" in vals:
        rev.setdefault(vals["en"], []).append(slug)
rev = {k: sorted(set(v)) for k, v in rev.items()}
with open(os.path.join(base, "i18n_reverse.json"), "w", encoding="utf-8") as f:
    json.dump(rev, f, ensure_ascii=False, indent=1)
print("i18n_reverse.json written:", len(rev), "ru->slug entries")
